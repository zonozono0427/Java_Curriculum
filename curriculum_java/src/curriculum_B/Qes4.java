public class Qes4 {

	public static void main(String[] args) {
		
		
		for (int i = 1; i <= 9; i++) {
            for (int j = 1; j <= 10; j++) {
                System.out.print(i + " x " + j + " = " + (i * j) + "\t||\t");
            }
            System.out.println();
        }

			
	
	}

}
